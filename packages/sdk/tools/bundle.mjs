// Moon's feature build implementation, intentionally outside the portable SDK.
// Bun's parser scans module exports without executing feature code on the build
// machine. Namespace registration at runtime and mapped TS types use the same
// definition brand, so aliases/reexports/wrapped builders need no AST heuristics.
import { mkdir, mkdtemp, rm, stat } from "node:fs/promises";
import { join, resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { workerSources } from "./worker.mjs";
import {
  bunPluginBoundary,
  checkPluginImports,
  featurePluginRoot,
  pluginCompilerOptions,
} from "./plugin-boundary.mjs";
import ts from "typescript";

import { isServerRoot, isServerModule } from "./server-files.mjs";

const sdkRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const quote = JSON.stringify;
const header = "// Generated by the sdk:bundle moon task. Do not edit.\n";

function apiType(modules, files) {
  const tree = new Map();
  for (const module of modules) {
    let node = tree;
    const parts = module.split("/");
    for (const [index, part] of parts.entries()) {
      const last = index === parts.length - 1;
      const existing = node.get(part);
      if ((last && existing !== undefined) || typeof existing === "string") {
        throw new Error(`API module path collision at ${module}; rename the file or folder`);
      }
      if (last)
        node.set(
          part,
          `ApiFromModule<typeof import(${quote("../" + files[modules.indexOf(module)].slice(0, -3))})>`,
        );
      else {
        if (existing === undefined) node.set(part, new Map());
        node = node.get(part);
      }
    }
  }

  const render = (node) =>
    "{\n" +
    [...node]
      .map(([key, value]) => `readonly ${quote(key)}: ${typeof value === "string" ? value : render(value)};`)
      .join("\n") +
    "\n}";
  return render(tree);
}

/** Called only by moon; there is no installable binary or SDK CLI. */
export async function bundleFeature(folder, namespace, worker = false) {
  const root = resolve(folder);
  if (!(await stat(root)).isDirectory()) throw new Error(`Feature root is not a directory: ${root}`);
  const pluginRoot = featurePluginRoot(root);
  checkPluginImports(pluginRoot);
  const files = await scanFiles(root);
  // An explicit empty product backend is valid; a missing root still fails.
  const organized = isServerRoot(root);
  const modules = files.map((file) => (organized ? file.split("/").at(-1).slice(0, -3) : file.slice(0, -3)));
  if (new Set(modules).size !== modules.length)
    throw new Error("Duplicate server module name; module basenames must be unique");
  const type = apiType(modules, files);
  const generated = join(root, "_generated");
  await mkdir(generated, { recursive: true });
  await Bun.write(
    join(generated, "api.ts"),
    header +
      'import { createApi, type ApiFromModule } from "@tokamak/sdk";\n' +
      `export const api = createApi<${type}>(${namespace ? JSON.stringify(namespace) : ""});\n`,
  );

  // Temporary entry/config live together and are always removed. They must
  // never be mistaken for author modules on the next build.
  const temporary = await mkdtemp(join(generated, "build-"));
  try {
    const hasSchema = await Bun.file(join(root, "schema.ts")).exists();
    const entry = join(temporary, "entry.ts");
    let source = featureSource(root, files, modules, hasSchema);
    let workerPlugins = [];
    if (worker) {
      const result = await workerSources({ root, files, modules, hasSchema, sdkRoot, header, pluginRoot });
      source = result.source;
      workerPlugins = result.plugins;
    }
    await Bun.write(entry, source);

    await checkFeature(root, temporary, generated, files, entry, worker);
    const built = await Bun.build({
      entrypoints: ["tokamak-feature:entry"],
      target: "browser",
      format: "esm",
      splitting: false,
      sourcemap: "linked",
      naming: "bundle.js",
      outdir: join(root, "dist"),
      packages: "bundle",
      env: "disable",
      allowUnresolved: [],
      plugins: [
        bunPluginBoundary(pluginRoot),
        ...workerPlugins,
        {
          name: "stable-feature-entry",
          setup(build) {
            build.onResolve({ filter: /^tokamak-feature:entry$/ }, () => ({
              path: "entry",
              namespace: "tokamak-feature",
            }));
            build.onLoad({ filter: /.*/, namespace: "tokamak-feature" }, () => ({
              contents: source,
              loader: "ts",
              resolveDir: root,
            }));
          },
        },
        {
          name: "portable-sdk",
          setup(build) {
            build.onResolve({ filter: /^@tokamak\/sdk$/ }, () => ({
              path: join(sdkRoot, "src/index.ts"),
            }));
          },
        },
      ],
    });
    if (!built.success) throw new AggregateError(built.logs, "Feature bundle failed");
    const chunks = built.outputs.filter((output) => output.kind !== "sourcemap");
    if (chunks.length !== 1 || !built.outputs.some((output) => output.kind === "sourcemap"))
      throw new Error("Feature build must produce exactly one ESM file and its source map");
    const scan = new Bun.Transpiler({ loader: "js" }).scan(await chunks[0].text());
    if (scan.imports.length !== 0)
      throw new Error("Feature bundle retains imports; the runtime loads only one module");
    console.log(`${relative(process.cwd(), root)} -> dist/bundle.js + source map, _generated/api.ts`);

    return {
      bundle: join(root, "dist/bundle.js"),
      api: join(generated, "api.ts"),
    };
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  if (
    process.argv.length !== 3 &&
    !(
      [5, 6].includes(process.argv.length) &&
      process.argv[3] === "--plugin" &&
      (process.argv.length === 5 || process.argv[5] === "--worker")
    )
  ) {
    throw new Error("sdk:bundle expects a feature folder and optional --plugin <id>");
  }
  // Moon runs the task in packages/sdk/. Arguments are workspace-relative for stable use
  // from either the repository root or the feature's own moon configuration.
  const feature = resolve(sdkRoot, "../..", process.argv[2]);
  // Bun's generated module comments/debug IDs must not depend on caller cwd.
  process.chdir(feature);
  await bundleFeature(feature, process.argv[4], process.argv[5] === "--worker");
}

async function scanFiles(root) {
  const files = [];
  const scanner = new Bun.Transpiler({ loader: "ts" });
  for await (const file of new Bun.Glob("**/*.ts").scan({
    cwd: root,
    onlyFiles: true,
  })) {
    if (!isServerModule(root, file)) continue;
    // scan is a real parser, not a regexp. We do not interpret initializer
    // syntax: exported definitions are recognized by their runtime brand.
    scanner.scan(await Bun.file(join(root, file)).text());
    files.push(file);
  }
  files.sort();
  return files;
}

async function checkFeature(root, temporary, generated, files, entry, worker) {
  const config = join(temporary, "tsconfig.json");
  // Inherit resolution options unchanged, including paths relative to the
  // config that declared them. A build-only SDK alias or TS-extension opt-in
  // would accept code that generated-reference consumers cannot type-check.
  const parentConfig = (await Bun.file(join(root, "tsconfig.json")).exists())
    ? join(root, "tsconfig.json")
    : join(sdkRoot, "../..", "tsconfig.json");
  const inherited = ts.getParsedCommandLineOfConfigFile(
    parentConfig,
    {},
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic() {} },
  );
  const paths = pluginCompilerOptions(featurePluginRoot(root), inherited?.options ?? {}).paths;
  await Bun.write(
    config,
    JSON.stringify({
      extends: parentConfig,
      compilerOptions: {
        lib: worker ? ["ES2022", "DOM"] : ["ES2022"],
        types: worker ? ["node"] : [],
        paths,
        noEmit: true,
        strict: true,
      },
      files: [entry, join(generated, "api.ts"), ...files.map((file) => join(root, file))],
      include: [],
      exclude: [],
    }),
  );
  const check = Bun.spawnSync([process.execPath, "check", "--no-script", "--project", config], {
    stdout: "inherit",
    stderr: "inherit",
  });
  if (check.exitCode !== 0) throw new Error("Feature type check failed (only ES2022 globals are allowed)");
}

function featureSource(root, files, modules, hasSchema) {
  const source =
    header +
    'import { createRegistry, functionMetadata, schemaMetadata, invokeFunction, type HostBridge, type JsonValue } from "@tokamak/sdk";\n' +
    files.map((file, i) => `import * as m${i} from ${quote(join(root, file.slice(0, -3)))};\n`).join("") +
    (hasSchema
      ? `import schemaValue from ${quote(join(root, "schema"))};\nexport const schema = schemaMetadata(schemaValue);\n`
      : "export const schema = schemaMetadata(null);\n") +
    `export const functions = createRegistry({${modules.map((module, i) => `${quote(module)}: m${i}`).join(",")}});\n` +
    "export const metadata = functionMetadata(functions);\n" +
    // Pool invokes functions only. Inspect the SAME registry/schema values,
    // without inventing a second build-time manifest or executing a handler.
    "export const describe = () => ({ schema, functions: metadata });\n" +
    "export const invoke = (request: {name: string; args: JsonValue}, host: HostBridge) => invokeFunction(functions, request, host);\n";
  return source;
}
