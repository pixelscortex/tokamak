const sdkRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const quote = JSON.stringify;
const useLocal = 'Move access to processes and files into a local function or an action with on: "caller".';
const useServer = "Call a server function for database access.";
const header = "// Generated by the sdk:bundle moon task. Do not edit.\n";

function apiType(modules, typeAt) {
  const tree = new Map();
  for (const [moduleIndex, module] of modules.entries()) {
    let node = tree;
    const parts = module.split("/");
    for (const [index, part] of parts.entries()) {
      const last = index === parts.length - 1;
      const existing = node.get(part);
      if ((last && existing !== undefined) || typeof existing === "string") {
        throw new Error(`API module path collision at ${module}; rename the file or folder`);
      }
      if (last) node.set(part, typeAt(moduleIndex));
      else {
        if (existing === undefined) node.set(part, new Map());
        node = node.get(part);
      }
    }
  }

  function render(node, depth = 0) {
    if (!node.size) return "{}";
    const indent = "  ".repeat(depth + 1);
    const fields = [...node].map(([key, value]) => {
      const type =
        typeof value === "string" ? value.replaceAll("\n", "\n" + indent) : render(value, depth + 1);
      return `${indent}readonly ${quote(key)}: ${type};`;
    });
    return `{\n${fields.join("\n")}\n${"  ".repeat(depth)}}`;
  }
  return render(tree);
}

function discoverReferences(root, pluginRoot, sources, virtual) {
  const config = ts.getParsedCommandLineOfConfigFile(
    ts.findConfigFile(root, ts.sys.fileExists) ?? join(sdkRoot, "../..", "tsconfig.json"),
    {},
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic() {} },
  );
  const options = pluginCompilerOptions(pluginRoot, config?.options ?? {});
  const host = ts.createCompilerHost(options);
  // Discover definitions from source types without loading plugin code or
  // depending on the last build's references. The virtual types bootstrap
  // plugins that already refer to their generated API from a handler.
  const { getSourceFile, fileExists } = host;
  host.fileExists = (path) => virtual.has(path) || fileExists(path);
  host.getSourceFile = (path, language, ...rest) =>
    virtual.has(path)
      ? ts.createSourceFile(path, virtual.get(path), language, true)
      : getSourceFile(path, language, ...rest);
  const program = ts.createProgram(sources, options, host);
  const checker = program.getTypeChecker();
  return sources.map((path) => {
    const source = program.getSourceFile(path);
    const symbol = checker.getSymbolAtLocation(source);
    if (!symbol) return [];
    const runtime = runtimeExportNames(checker, symbol);
    return checker
      .getExportsOfModule(symbol)
      .filter((entry) => runtime.has(entry.name))
      .flatMap((entry) => {
        const info = definitionInfo(checker, entry, source);
        if (!info) return [];
        if (info.visibility === undefined)
          throw new Error(
            `Cannot determine visibility of ${path}:${entry.name}; preserve the function builder's inferred type`,
          );
        return [{ name: entry.name, visibility: info.visibility }];
      })
      .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  });
}

async function generateReferences(root, pluginRoot, files, modules, namespace) {
  const generated = join(root, "_generated");
  const variants = [
    { name: "api", mapping: "ApiFromModule", visibility: Visibility.Public },
    { name: "internal", mapping: "InternalFromModule", visibility: Visibility.Internal },
    { name: "plugin", mapping: "PluginFunctionsFromModule", visibility: Visibility.PluginOnly },
  ];
  const pathFor = (variant) => join(generated, variant.name + ".ts");
  function render(name, mapping, type, names) {
    const list = names?.length ? `[\n${names.map((name) => "  " + quote(name) + ",").join("\n")}\n]` : "[]";
    return (
      header +
      `import { createApi${mapping ? ", type " + mapping : ""} } from "@tokamak/sdk";\n` +
      `type References = ${type};\n` +
      `export const ${name}: References = createApi(${quote(namespace) ?? "undefined"}${names ? ", " + list : ""});\n`
    );
  }
  const importType = (index) => `typeof import(${quote("../" + files[index].replace(/\.tsx?$/, ""))})`;
  const virtual = new Map(
    variants.map((variant) => [
      pathFor(variant),
      render(
        variant.name,
        variant.mapping,
        apiType(modules, (i) => `${variant.mapping}<${importType(i)}>`),
      ),
    ]),
  );
  const exports = discoverReferences(
    root,
    pluginRoot,
    files.map((file) => join(root, file)),
    virtual,
  );
  await mkdir(generated, { recursive: true });
  for (const variant of variants) {
    const groups = exports.map((entries) =>
      entries.filter((entry) => entry.visibility === variant.visibility),
    );
    const included = modules.flatMap((_, i) => (groups[i].length ? [i] : []));
    const names = groups.flatMap((group, i) => group.map((entry) => `${modules[i]}:${entry.name}`));
    const type = apiType(
      included.map((i) => modules[i]),
      (index) => {
        const i = included[index];
        return (
          "{\n" +
          groups[i]
            .map(
              ({ name }) =>
                `  readonly ${quote(name)}: ReferenceFromDefinition<${importType(i)}[${quote(name)}]>;`,
            )
            .join("\n") +
          "\n}"
        );
      },
    );
    const output = render(variant.name, names.length ? "ReferenceFromDefinition" : null, type, names);
    const destination = Bun.file(pathFor(variant));
    const existed = await destination.exists();
    if (variant.visibility === Visibility.PluginOnly && !names.length && !existed) continue;
    if (!existed || (await destination.text()) !== output) await Bun.write(destination, output);
  }
}

/** Called only by moon; there is no installable binary or SDK CLI. */
export async function bundleFeature(folder, namespace, splitActions = namespace !== undefined) {
  const root = await realpath(folder);
  if (!(await stat(root)).isDirectory()) throw new Error(`Feature root is not a directory: ${root}`);
  // A flat plugin has its server entry at src/, even without a plugin.ts descriptor.
  const pluginRoot =
    namespace !== undefined && basename(root) === "src" ? dirname(root) : featurePluginRoot(root);
  checkPluginImports(pluginRoot);
  // An explicit empty plugin server part is valid; a missing root still fails.
  const organized = isServerRoot(root);
  const flat = root === join(pluginRoot, "src");
  const pluginSource = organized || flat;
  const placement = pluginSource ? functionPlacement(pluginRoot, undefined, namespace) : undefined;
  const providers = placement?.providers ?? [];
  const local = placement
    ? placedModules(
        placement,
        root,
        organized,
        namespace === undefined ? (kind) => kind === "local" : runnerFunction,
      )
    : [];
  const split =
    !!placement &&
    (local.length > 0 ||
      flat ||
      (organized && [...placement.modules.keys()].some((path) => !path.startsWith(root + sep))));
  const server = split ? placedModules(placement, root, organized, (kind) => kind !== "local") : [];
  const files = split
    ? [...new Set([...server, ...local].map(([path]) => relative(root, path).split(sep).join("/")))]
    : await scanFiles(root);
  const modules = split
    ? files.map((file) => [...server, ...local].find(([path]) => path === resolve(root, file))[1])
    : files.map((file) => (organized ? file.split("/").at(-1).slice(0, -3) : file.slice(0, -3)));
  if (new Set(modules).size !== modules.length)
    throw new Error("Duplicate server module name; module basenames must be unique");
  const generated = join(root, "_generated");
  await generateReferences(root, pluginRoot, files, modules, namespace);

  // Temporary entry/config live together and are always removed. They must
  // never be mistaken for author modules on the next build.
  const temporary = await mkdtemp(join(generated, "build-"));
  try {
    const hasSchema = await Bun.file(join(root, "schema.ts")).exists();
    const entry = join(temporary, "entry.ts");
    const source = registrySource({
      root,
      modules: split ? server : files.map((file, i) => [join(root, file), modules[i]]),
      hasSchema,
      results: placement?.results(root, organized),
      providers,
      header,
    });
    await Bun.write(entry, source);

    const hasLocal =
      local.length > 0 ||
      providers.some(namespace === undefined ? (p) => p.place === "local" : runnerProvider);
    if (hasLocal) {
      await buildLocalBundle({
        root,
        sdkRoot,
        pluginRoot,
        source: registrySource({ root, modules: local, providers, lane: lanes.local, worker: true, header }),
        plugins: [placementTransform(placement, lanes.local)],
        actionModules: runnerActionFiles(placement.modules, providers),
      });
      // Preserve the installed-artifact and socket entryHash contract. No
      // executable entry is needed: the plugin process loads local.js.
      await Bun.write(join(root, "dist/local-entry.js"), "");
    }
    async function buildServer(naming, contents, plugins) {
      const built = await Bun.build({
        entrypoints: ["tokamak-feature:entry"],
        target: "browser",
        format: "esm",
        splitting: false,
        sourcemap: "linked",
        naming,
        outdir: join(root, "dist"),
        packages: "bundle",
        env: "disable",
        allowUnresolved: [],
        plugins: [
          bunPluginBoundary(pluginRoot),
          ...plugins,
          {
            name: "stable-feature-entry",
            setup(build) {
              build.onResolve({ filter: /^tokamak-feature:entry$/ }, () => ({
                path: "entry",
                namespace: "tokamak-feature",
              }));
              build.onLoad({ filter: /.*/, namespace: "tokamak-feature" }, () => ({
                contents,
                loader: "ts",
                resolveDir: root,
              }));
            },
          },
          {
            name: "portable-sdk",
            setup(build) {
              build.onResolve({ filter: /^@tokamak\/sdk$/ }, () => ({
                path: join(sdkRoot, "src/index.ts"),
              }));
            },
          },
        ],
      });
      if (!built.success) throw new AggregateError(built.logs, "Feature bundle failed");
      return built;
    }
    const stubImporters = new Set();
    const built = await buildServer("bundle.js", source, [
      ...(placement ? [placementTransform(placement, lanes.server)] : []),
      serverBuiltins("server-local-boundary", pluginRoot, "queries, mutations and server actions", {
        callerFiles: placement?.callerFiles,
        onStub: (path) => stubImporters.add(relative(pluginRoot, path)),
      }),
    ]);
    if (stubImporters.size) {
      try {
        await import(join(root, "dist/bundle.js"));
      } catch (error) {
        if (!(error instanceof Error) || error.kind !== "noMachine") throw error;
        throw new Error(
          `Plugin import boundary: a Runner binding from ${[...stubImporters].join(", ")} was used at module load. Move it inside the handler.\n${error.stack}`,
          { cause: error },
        );
      }
    }
    if (splitActions) {
      const descriptor = transactionSources({
        root,
        files,
        modules,
        hasSchema,
        header,
        pluginRoot,
        placement: split ? placement : undefined,
        namespace,
      });
      await buildServer("transactions.js", descriptor.source, descriptor.plugins);
    }
    // Report unsupported imports before TypeScript reports missing Node declarations.
    await checkFeature(root, temporary, generated, files, entry, hasLocal, providers);
    if (namespace !== undefined)
      await Bun.write(
        join(root, "dist/contracts.json"),
        JSON.stringify(contractManifest(pluginRoot, namespace, providers)),
      );
    const chunks = built.outputs.filter((output) => output.kind !== "sourcemap");
    if (chunks.length !== 1 || !built.outputs.some((output) => output.kind === "sourcemap"))
      throw new Error("Feature build must produce exactly one ESM file and its source map");
    const scan = new Bun.Transpiler({ loader: "js" }).scan(await chunks[0].text());
    if (scan.imports.length !== 0)
      throw new Error("Feature bundle retains imports; the runtime loads only one module");
    console.log(
      `${relative(process.cwd(), root)} -> dist/bundle.js + source map, _generated/{api,internal}.ts`,
    );

    return {
      bundle: join(root, "dist/bundle.js"),
      api: join(generated, "api.ts"),
    };
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  if (process.argv.length !== 3 && !(process.argv.length === 5 && process.argv[3] === "--plugin")) {
    throw new Error("sdk:bundle expects a feature folder and optional --plugin <id>");
  }
  // Moon runs the task in packages/sdk/. Arguments are workspace-relative for stable use
  // from either the repository root or the feature's own moon configuration.
  const feature = resolve(sdkRoot, "../..", process.argv[2]);
  // Bun's generated module comments/debug IDs must not depend on caller cwd.
  process.chdir(feature);
  await bundleFeature(feature, process.argv[4], true);
}

async function scanFiles(root) {
  const files = [];
  const scanner = new Bun.Transpiler({ loader: "ts" });
  for await (const scanned of new Bun.Glob("**/*.ts").scan({
    cwd: root,
    onlyFiles: true,
  })) {
    const file = scanned.split(sep).join("/");
    if (!isServerModule(root, file)) continue;
    // scan is a real parser, not a regexp. We do not interpret initializer
    // syntax: exported definitions are recognized by their runtime brand.
    scanner.scan(await Bun.file(join(root, file)).text());
    files.push(file);
  }
  files.sort();
  return files;
}

async function checkFeature(root, temporary, generated, files, entry, hasLocal, providers) {
  const config = join(temporary, "tsconfig.json");
  // Inherit resolution options unchanged, including paths relative to the
  // config that declared them. A build-only SDK alias or TS-extension opt-in
  // would accept code that generated-reference consumers cannot type-check.
  const parentConfig = (await Bun.file(join(root, "tsconfig.json")).exists())
    ? join(root, "tsconfig.json")
    : join(sdkRoot, "../..", "tsconfig.json");
  const inherited = ts.getParsedCommandLineOfConfigFile(
    parentConfig,
    {},
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic() {} },
  );
  const paths = pluginCompilerOptions(featurePluginRoot(root), inherited?.options ?? {}).paths;
  await Bun.write(
    config,
    JSON.stringify({
      extends: parentConfig,
      compilerOptions: {
        lib: hasLocal ? ["ES2022", "DOM"] : ["ES2022"],
        types: hasLocal ? ["node"] : [],
        paths,
        noEmit: true,
        strict: true,
      },
      files: [
        entry,
        join(generated, "api.ts"),
        join(generated, "internal.ts"),
        ...new Set([
          ...files.map((file) => join(root, file)),
          ...providers.map((p) => p.path),
          ...[contractEntry(featurePluginRoot(root))].filter(ts.sys.fileExists),
        ]),
      ],
      include: [],
      exclude: [],
    }),
  );
  const check = Bun.spawnSync([process.execPath, "check", "--no-script", "--project", config]);
  const stdout = check.stdout.toString();
  const stderr = check.stderr.toString();
  if (stdout) process.stdout.write(stdout);
  if (stderr) process.stderr.write(stderr);
  if (check.exitCode !== 0) {
    const diagnostics = (stdout + stderr).replace(/\x1b\[[0-9;]*m/g, "");
    const advice = [];
    if (
      /Property 'proc' does not exist on type .*?(?:Query|Mutation|Action)Context/.test(diagnostics) ||
      [...diagnostics.matchAll(/Cannot find module '([^']+)'/g)].some(([, path]) =>
        /^(?:node:)?fs\/promises$/.test(path),
      )
    )
      advice.push(useLocal);
    if (/Property 'db' does not exist on type 'LocalContext'/.test(diagnostics)) advice.push(useServer);
    throw new Error(["Feature type check failed.", ...advice].join(" "));
  }
}
